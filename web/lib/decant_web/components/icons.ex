  defp server_path(nil), do: @mcp
  defp server_path(""), do: @mcp

  defp server_path(server) do
    s = String.downcase(server)
    Enum.find_value(@servers, @mcp, fn {key, d} -> if String.contains?(s, key), do: d end)
  end

  @doc "Which brand a model id belongs to: :claude | :openai | :other."
  def brand(nil), do: :other

  def brand(model) do
    m = String.downcase(model)

    cond do
      String.contains?(m, "claude") -> :claude
      String.contains?(m, "opus") -> :claude
      String.contains?(m, "sonnet") -> :claude
      String.contains?(m, "haiku") -> :claude
      String.contains?(m, "gpt") -> :openai
      String.contains?(m, "codex") -> :openai
      String.starts_with?(m, "o1") -> :openai
      String.starts_with?(m, "o3") -> :openai
      true -> :other
    end
  end
